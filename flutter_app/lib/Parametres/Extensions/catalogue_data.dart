import 'extension_item.dart';

/// Entrée de catalogue (serveur MCP, outil ou skill à installer).
class CatalogEntry {
  final String id;
  final String name;
  final String description;
  final String url;
  final String command;
  final String category;
  final String stars;

  const CatalogEntry({
    required this.id,
    required this.name,
    required this.description,
    required this.url,
    this.command = '',
    this.category = '',
    this.stars = '',
  });

  ExtensionItem toItem(ExtensionKind kind) => ExtensionItem(
        id: id,
        name: name,
        description: description,
        kind: kind,
        icon: switch (kind) {
          ExtensionKind.mcp => 'hub',
          ExtensionKind.tool => 'build',
          ExtensionKind.skill => 'auto_awesome',
        },
        config: {
          if (url.isNotEmpty) 'url': url,
          if (command.isNotEmpty) 'command': command,
          if (category.isNotEmpty) 'category': category,
        },
      );
}

